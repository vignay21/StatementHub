SUPABASE_SCHEMA_SQL = """-- Run this in Supabase SQL Editor (https://supabase.com/dashboard/project/_/sql)

-- 1. Table for bank transactions (with automatic deduplication)
create table if not exists transactions (
    id bigint generated by default as identity primary key,
    fingerprint text unique not null,
    bank text not null,
    date text not null,
    description text not null,
    party_name text default '',
    amount numeric not null,
    type text not null,
    utr text default '',
    balance numeric,
    party_match_key text not null,
    source_file text default '',
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Indexes for lightning fast searches
create index if not exists idx_transactions_utr on transactions(utr);
create index if not exists idx_transactions_date on transactions(date);
create index if not exists idx_transactions_fingerprint on transactions(fingerprint);
create index if not exists idx_transactions_match_key on transactions(party_match_key);

-- 2. Table for reusable party / vendor mappings
create table if not exists party_mappings (
    match_key text primary key,
    party_name text not null,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);
"""


def clean_str(val: Any) -> str:
    if val is None or pd.isna(val):
        return ""
    text = re.sub(r"\s+", " ", str(val)).strip()
    if text.startswith('="') and text.endswith('"'):
        text = text[2:-1].strip()
    elif text.startswith("="):
        text = text[1:].strip().strip('"\'')
    return text


def compute_transaction_fingerprint(row: dict[str, Any]) -> str:
    """Generate a stable fingerprint independent of the upload file name.

    Deduplicates overlapping daily statements while preserving legitimate
    identical amounts (via unique UTRs, closing balances, or timestamps).
    """
    amount = row.get("Amount")
    amount_str = f"{float(amount):.2f}" if amount is not None and not pd.isna(amount) else "0.00"
    balance = row.get("Balance")
    balance_str = f"{float(balance):.2f}" if balance is not None and not pd.isna(balance) else ""

    parts = [
        clean_str(row.get("Bank")),
        clean_str(row.get("Date")),
        amount_str,
        clean_str(row.get("Type")),
        clean_str(row.get("UTR / Reference")),
        clean_str(row.get("Description")),
        balance_str,
    ]
    return hashlib.sha256("|".join(parts).encode("utf-8")).hexdigest()


def get_supabase_client() -> Client | None:
    """Retrieve an authenticated Supabase client from Streamlit secrets or env vars."""
    if create_client is None:
        return None

    url = None
    key = None

    if st is not None and hasattr(st, "secrets") and "supabase" in st.secrets:
        url = st.secrets["supabase"].get("url")
        key = st.secrets["supabase"].get("key")

    if not url or not key:
        url = os.environ.get("SUPABASE_URL")
        key = os.environ.get("SUPABASE_KEY")

    if not url or not key:
        return None

    try:
        return create_client(url, key)
    except Exception:
        return None


def fetch_party_names(client: Client) -> list[str]:
    """Fetch all distinct stored party names from Supabase for auto-completion."""
    names: set[str] = set()
    # 1. Try from party_names table if exists
    try:
        res = client.table("party_names").select("name").execute()
        for item in res.data:
            val = clean_str(item.get("name"))
            if val:
                names.add(val)
    except Exception:
        pass

    # 2. Try from party_mappings table (existing schema store)
    try:
        res = client.table("party_mappings").select("party_name").execute()
        for item in res.data:
            val = clean_str(item.get("party_name"))
            if val:
                names.add(val)
    except Exception:
        pass

    # 3. From transactions table where party_name != ''
    try:
        res = client.table("transactions").select("party_name").neq("party_name", "").limit(5000).execute()
        for item in res.data:
            val = clean_str(item.get("party_name"))
            if val:
                names.add(val)
    except Exception:
        pass

    return sorted(names)


def save_party_name(client: Client, party_name: str) -> bool:
    """Save a party name to Supabase suggestions store."""
    party_name = clean_str(party_name)
    if not party_name:
        return False
    saved = False
    try:
        client.table("party_names").upsert({"name": party_name}).execute()
        saved = True
    except Exception:
        pass
    try:
        client.table("party_mappings").upsert({
            "match_key": party_name.lower(),
            "party_name": party_name,
        }).execute()
        saved = True
    except Exception:
        pass
    return saved


def delete_party_name(client: Client, party_name: str) -> bool:
    """Remove a party name from Supabase suggestions store."""
    party_name = clean_str(party_name)
    if not party_name:
        return False
    try:
        client.table("party_names").delete().eq("name", party_name).execute()
    except Exception:
        pass
    try:
        client.table("party_mappings").delete().eq("match_key", party_name.lower()).execute()
    except Exception:
        pass
    return True


def update_transaction_party(client: Client, fingerprint: str, party_name: str) -> bool:
    """Update party_name for a single transaction in Supabase."""
    try:
        client.table("transactions").update({
            "party_name": clean_str(party_name),
        }).eq("fingerprint", fingerprint).execute()
        return True
    except Exception:
        return False


def update_transactions_party_bulk(client: Client, fingerprints: list[str], party_name: str) -> bool:
    """Update party_name for multiple transactions in Supabase in chunks."""
    if not fingerprints:
        return True
    try:
        clean_name = clean_str(party_name)
        chunk_size = 100
        for i in range(0, len(fingerprints), chunk_size):
            chunk = fingerprints[i:i + chunk_size]
            client.table("transactions").update({
                "party_name": clean_name,
            }).in_("fingerprint", chunk).execute()
        return True
    except Exception:
        return False


def fetch_party_mappings(client: Client) -> dict[str, str]:
    """Fetch all reusable party mappings from Supabase."""
    try:
        response = client.table("party_mappings").select("match_key, party_name").execute()
        return {item["match_key"]: item["party_name"] for item in response.data}
    except Exception:
        return {}


def save_party_mapping(client: Client, match_key: str, party_name: str) -> bool:
    """Save or update a reusable party mapping and update existing matching transactions."""
    try:
        client.table("party_mappings").upsert({
            "match_key": match_key,
            "party_name": party_name,
        }).execute()

        # Update all matching transactions in Supabase
        client.table("transactions").update({
            "party_name": party_name,
        }).eq("party_match_key", match_key).execute()
        return True
    except Exception:
        return False


def delete_party_mapping(client: Client, match_key: str) -> bool:
    """Remove a party mapping and reset matching transactions."""
    try:
        client.table("party_mappings").delete().eq("match_key", match_key).execute()
        client.table("transactions").update({
            "party_name": "",
        }).eq("party_match_key", match_key).execute()
        return True
    except Exception:
        return False


def clear_all_party_mappings(client: Client) -> bool:
    """Clear all party mappings in Supabase."""
    try:
        client.table("party_mappings").delete().neq("match_key", "").execute()
        client.table("transactions").update({"party_name": ""}).neq("fingerprint", "").execute()
        return True
    except Exception:
        return False


def save_transaction_override(client: Client, fingerprint: str, party_name: str) -> bool:
    """Save an override for a single transaction in Supabase."""
    return update_transaction_party(client, fingerprint, party_name)


def sync_transactions_with_dedup(client: Client, df: pd.DataFrame) -> tuple[int, int]:
    """Insert new transactions into Supabase, automatically skipping duplicates.

    Uses a two-layer deduplication check:
    1. SHA-256 transaction fingerprint.
    2. Bank + Date + Amount + Type + UTR signature (when UTR is non-empty).

    Returns (new_inserted_count, duplicates_skipped_count).
    """
    if df.empty:
        return 0, 0

    records: list[dict[str, Any]] = []
    fingerprints: list[str] = []
    valid_utrs: list[str] = []

    for _, row in df.iterrows():
        fp = row.get("fingerprint") or compute_transaction_fingerprint(row.to_dict())
        fingerprints.append(fp)
        utr_val = clean_str(row.get("UTR / Reference"))
        if utr_val:
            valid_utrs.append(utr_val)
        records.append({
            "fingerprint": fp,
            "bank": clean_str(row.get("Bank")),
            "date": clean_str(row.get("Date")),
            "description": clean_str(row.get("Description")),
            "party_name": clean_str(row.get("Party Name")),
            "amount": float(row.get("Amount", 0)) if row.get("Amount") is not None and not pd.isna(row.get("Amount")) else 0.0,
            "type": clean_str(row.get("Type")),
            "utr": utr_val,
            "balance": float(row.get("Balance")) if row.get("Balance") is not None and not pd.isna(row.get("Balance")) else None,
            "party_match_key": clean_str(row.get("Party match key")),
            "source_file": clean_str(row.get("Source file")),
        })

    # Layer 1: Query existing fingerprints in Supabase (in chunks of 200)
    existing_fps: set[str] = set()
    chunk_size = 200
    for i in range(0, len(fingerprints), chunk_size):
        chunk = fingerprints[i:i + chunk_size]
        try:
            res = client.table("transactions").select("fingerprint").in_("fingerprint", chunk).execute()
            for item in res.data:
                existing_fps.add(item["fingerprint"])
        except Exception:
            pass

    # Layer 2: Query existing (bank, date, amount, type, utr) for populated UTRs
    existing_utr_keys: set[tuple[str, str, float, str, str]] = set()
    if valid_utrs:
        for i in range(0, len(valid_utrs), chunk_size):
            u_chunk = valid_utrs[i:i + chunk_size]
            try:
                res = client.table("transactions").select("bank, date, amount, type, utr").in_("utr", u_chunk).execute()
                for item in res.data:
                    existing_utr_keys.add((
                        clean_str(item.get("bank")),
                        clean_str(item.get("date")),
                        float(item.get("amount", 0)),
                        clean_str(item.get("type")),
                        clean_str(item.get("utr")),
                    ))
            except Exception:
                pass

    to_insert = []
    for r in records:
        if r["fingerprint"] in existing_fps:
            continue
        if r["utr"]:
            key = (r["bank"], r["date"], r["amount"], r["type"], r["utr"])
            if key in existing_utr_keys:
                continue
        to_insert.append(r)

    skipped_count = len(records) - len(to_insert)

    if to_insert:
        # Insert in chunks of 100
        for i in range(0, len(to_insert), 100):
            sub_chunk = to_insert[i:i + 100]
            client.table("transactions").insert(sub_chunk).execute()

    return len(to_insert), skipped_count


def fetch_all_transactions(client: Client, limit: int = 50000) -> pd.DataFrame:
    """Fetch stored transactions from Supabase into a DataFrame using pagination."""
    try:
        all_data: list[dict[str, Any]] = []
        page_size = 1000
        start = 0

        while start < limit:
            end = min(start + page_size - 1, limit - 1)
            response = (
                client.table("transactions")
                .select("id, fingerprint, bank, date, description, party_name, amount, type, utr, balance, party_match_key, source_file")
                .order("id", desc=True)
                .range(start, end)
                .execute()
            )
            if not response.data:
                break
            all_data.extend(response.data)
            if len(response.data) < page_size:
                break
            start += page_size

        if not all_data:
            return pd.DataFrame()

        rows = []
        for r in all_data:
            rows.append({
                "Bank": r["bank"],
                "Date": r["date"],
                "Description": r["description"],
                "Party Name": r["party_name"] or "",
                "Amount": float(r["amount"]) if r["amount"] is not None else 0.0,
                "Type": r["type"],
                "UTR / Reference": r["utr"] or "",
                "Balance": float(r["balance"]) if r["balance"] is not None else None,
                "Party match key": r["party_match_key"] or "",
                "Source file": r["source_file"] or "",
                "Transaction key": r["fingerprint"],
                "fingerprint": r["fingerprint"],
                "Original columns": {},
            })

        df = pd.DataFrame(rows)
        ids = df["UTR / Reference"]
        df["Duplicate UTR"] = ids.ne("") & ids.duplicated(keep=False)
        return df
    except Exception:
        return pd.DataFrame()


STORAGE_RPC_SQL = """-- Optional: Run in Supabase SQL Editor for 100% exact live disk usage
create or replace function get_storage_stats()
returns jsonb
language plpgsql
security definer
as $$
declare
  total_bytes bigint;
  table_bytes bigint;
  txn_count bigint;
begin
  select pg_database_size(current_database()) into total_bytes;
  select coalesce(pg_total_relation_size('transactions'), 0) into table_bytes;
  select count(*) into txn_count from transactions;
  return jsonb_build_object(
    'database_bytes', total_bytes,
    'table_bytes', table_bytes,
    'txn_count', txn_count
  );
end;
$$;
"""


def get_database_storage_stats(client: Client | None, df: pd.DataFrame | None = None) -> dict[str, Any]:
    """Calculate and return comprehensive database storage statistics.

    Directly queries Supabase for live record count, calculates serialized payload
    size, and accounts for PostgreSQL disk page overhead and B-tree indexes (~1.35x).
    """
    total_quota_mb = 500.0  # Supabase Free Tier limit
    txn_count = len(df) if df is not None and not df.empty else 0
    table_bytes = 0
    is_exact = False

    if client:
        # 1. Check if custom RPC get_storage_stats is present
        try:
            res = client.rpc("get_storage_stats").execute()
            if res.data and isinstance(res.data, dict):
                db_bytes = int(res.data.get("database_bytes", 0))
                table_bytes = int(res.data.get("table_bytes", table_bytes))
                txn_count = int(res.data.get("txn_count", txn_count))
                is_exact = True
                table_mb = table_bytes / (1024 * 1024)
                used_mb = db_bytes / (1024 * 1024)
                free_mb = max(0.0, total_quota_mb - used_mb)
                used_pct = min(100.0, (used_mb / total_quota_mb) * 100)
                remaining_txns = int((free_mb * 1024 * 1024) / 740) if free_mb > 0 else 0
                return {
                    "is_connected": True,
                    "is_exact": True,
                    "txn_count": txn_count,
                    "table_bytes": table_bytes,
                    "table_mb": round(table_mb, 2),
                    "used_mb": round(used_mb, 2),
                    "free_mb": round(free_mb, 2),
                    "total_quota_mb": total_quota_mb,
                    "used_pct": round(used_pct, 2),
                    "remaining_txns": remaining_txns,
                }
        except Exception:
            pass

        # 2. If txn_count is 0 or df is not provided, query live exact row count from Supabase
        if txn_count == 0:
            try:
                cnt_res = client.table("transactions").select("id", count="exact").limit(1).execute()
                if cnt_res.count is not None:
                    txn_count = cnt_res.count
            except Exception:
                pass

    # 3. Calculate accurate storage from record payload + Postgres B-tree index structures (~1.35x)
    if df is not None and not df.empty:
        try:
            raw_payload = len(df.to_json(orient="records").encode("utf-8"))
            table_bytes = int(raw_payload * 1.35)
        except Exception:
            table_bytes = txn_count * 740
    else:
        table_bytes = txn_count * 740

    table_mb = table_bytes / (1024 * 1024)
    used_mb = table_mb
    free_mb = max(0.0, total_quota_mb - used_mb)
    used_pct = min(100.0, (used_mb / total_quota_mb) * 100)
    bytes_per_txn = (table_bytes / txn_count) if txn_count > 0 else 740
    remaining_txns = int((free_mb * 1024 * 1024) / bytes_per_txn) if free_mb > 0 else 0

    return {
        "is_connected": bool(client),
        "is_exact": is_exact,
        "txn_count": txn_count,
        "table_bytes": table_bytes,
        "table_mb": round(table_mb, 2),
        "used_mb": round(used_mb, 2),
        "free_mb": round(free_mb, 2),
        "total_quota_mb": total_quota_mb,
        "used_pct": round(used_pct, 2),
        "remaining_txns": remaining_txns,
    }
